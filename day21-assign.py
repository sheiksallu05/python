
# ---Creating django application---

"1)Open command prompt run as Administrator mode"
"2)Checking python version"
    # python --version
"3)Create Virtual Environment"
    # python -m venv myworld
"4)Activate Virtual Environment"
    # myworld\scripts\activate.bat
"5)Install Django"
    # python -m pip install django
"6)Enter Virtual Environment Folder"
    # cd myworld
"7)Checking Django Version"
    # django-admin --version
"8)Create Django Project"
    # django-admin startproject project1
"9)Enter Project Folder"
    # cd project1
"10)Run Django Server"
    # python manage.py runserver
'''11)After Run this command - python manage.py runserver
      The server will start successfully and The URL will be displayed in the terminal
      http://127.0.0.1:8000/
      Open the URL in your browser.
      Verify the Django application output.'''
"12)Stop Django Server"
    # Ctrl+c
"13)Go Back One Folder"
    # cd..
"14)Deactivate Virtual Environment"
    # scripts\deactivate.bat

