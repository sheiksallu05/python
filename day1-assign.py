#2. Object-Oriented Programming Approach

"""Object-Oriented Programming (OOP) is a programming approach based on objects and classes.
An object contains data and functions that work with that data."""

#Main concepts of OOP:

"""1. Class - A blueprint for creating objects.
2. Object - An instance of a class.
3. Encapsulation - Combining data and methods together.
4. Inheritance - One class can inherit properties and methods from another class.
5. Polymorphism - The same method can perform different tasks.
6. Abstraction - Hiding unnecessary implementation details."""